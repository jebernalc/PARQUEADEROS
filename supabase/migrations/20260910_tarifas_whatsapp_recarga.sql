alter table if exists public.sesiones add column if not exists perfil text default 'INVITADO';
alter table if exists public.sesiones add column if not exists cortesia boolean default false;
alter table if exists public.sesiones add column if not exists recibido_por text;
alter table if exists public.sesiones add column if not exists medio_pago text;
alter table if exists public.sesiones add column if not exists recibo_digital text;
alter table if exists public.recargas add column if not exists minutos integer;
alter table if exists public.recargas add column if not exists tarifa numeric(12,2) default 0;
